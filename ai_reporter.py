_TRIAGE_METRICS_RE = re.compile(r"<!--\s*TRIAGE_METRICS:\s*suppressed=(\d+)\s*-->", re.IGNORECASE)


def _format_findings_for_prompt(findings: list[dict]) -> str:
    """
    Convert enriched findings into structured intelligence cards for Gemini.

    Rather than sending a raw JSON blob, each finding is formatted as a
    human-readable card so the model clearly sees every enrichment signal.
    This improves triage accuracy and reduces hallucination.
    """
    cards: list[str] = []

    for i, f in enumerate(findings, start=1):
        cve = f.get("cve") or "None"
        cvss_score = f.get("cvss_score")
        cvss_sev = f.get("cvss_severity") or "N/A"
        cvss_vec = f.get("cvss_vector") or "N/A"
        cwe = f.get("cwe_id") or "N/A"
        epss = f.get("epss_score")
        epss_pct = f.get("epss_percentile")
        in_kev = f.get("in_kev", False)
        kev_date = f.get("kev_due_date") or "N/A"
        kev_ransomware = f.get("kev_ransomware")

        # Format EPSS line
        if epss is not None:
            epss_pct_label = f" (top {(1 - epss_pct) * 100:.1f}%% of all CVEs)" if epss_pct else ""
            epss_line = f"{epss:.4f} — {epss * 100:.1f}% exploitation probability in next 30 days{epss_pct_label}"
        else:
            epss_line = "No EPSS record (CVE not yet scored or no CVE)"

        # Format KEV line
        if in_kev:
            kev_line = f"YES — CISA mandated remediation by {kev_date}"
            if kev_ransomware:
                kev_line += f" | Linked to ransomware campaigns: {kev_ransomware}"
        else:
            kev_line = "No"

        card = f"""--- FINDING #{i} ---
Template ID   : {f.get('template_id', 'N/A')}
Category      : {f.get('category', 'N/A')}
Scan Type     : {f.get('scan_type', 'N/A')}
Severity      : {f.get('severity', 'N/A').upper()}
Host          : {f.get('host', 'N/A')}
URL           : {f.get('url', 'N/A')}
Description   : {f.get('description', 'N/A')}
Evidence      : {f.get('evidence', 'N/A')}

--- CVE & THREAT INTELLIGENCE ---
CVE ID        : {cve}
CVSS Score    : {cvss_score if cvss_score is not None else 'N/A'} ({cvss_sev})
CVSS Vector   : {cvss_vec}
CWE           : {cwe}
NVD Desc.     : {f.get('nvd_description') or 'N/A'}
EPSS          : {epss_line}
CISA KEV      : {kev_line}
"""
        cards.append(card)

    return "\n".join(cards)


def _assessment_targets(findings: list[dict]) -> list[str]:
    """Return unique origins for the report scope without changing findings."""
    targets: list[str] = []
    for finding in findings:
        url = finding.get("url", "")
        parsed = urlsplit(url)
        target = f"{parsed.scheme}://{parsed.netloc}" if parsed.scheme and parsed.netloc else finding.get("host", "")
        if target and target not in targets:
            targets.append(target)
    return targets or ["No target URL recorded"]


def _suppressed_count(report_markdown: str, raw_count: int) -> tuple[int, str]:
    """Read the model's triage count, with a conservative report-text fallback."""
    metric = _TRIAGE_METRICS_RE.search(report_markdown)
    if metric:
        return min(int(metric.group(1)), raw_count), report_markdown

    logger.warning("Gemini omitted TRIAGE_METRICS; deriving suppressed count from its appendix labels.")
    count = len(re.findall(r"\bFALSE[_ ]POSITIVE\b", report_markdown, re.IGNORECASE))
    return min(count, raw_count), report_markdown


def generate_report(input_file: str, output_file: str) -> None:
    # Read the key at call time so it picks up the value set by show_startup_ui()
    # in main.py after the module was imported.
    api_key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not api_key:
        raise ValueError("GEMINI_API_KEY is required to generate the AI triage report.")

    input_path = Path(input_file)
    if not input_path.exists():
        logger.error("Input file %s not found.", input_file)
        raise FileNotFoundError(f"Input file not found: {input_file}")

    try:
        with open(input_path, "r", encoding="utf-8") as f:
            enriched_findings = json.load(f)
    except json.JSONDecodeError as exc:
        logger.error("Failed to parse JSON from %s: %s", input_file, exc)
        raise ValueError(f"Invalid JSON in {input_file}") from exc

    logger.info("Loaded %d enriched findings from %s.", len(enriched_findings), input_file)

    # Initialize the client with the key read from the environment at call time.
    client = genai.Client(api_key=api_key)
    
    # Model priority order — all confirmed available via API (curl verified).
    # gemini-2.0-flash is kept as the last fallback (confirmed HTTP 200 in prior runs).
    # gemini-1.5-x NOT used — old generation, potentially deprecated.
    CANDIDATE_MODELS = [
        "gemini-3.6-flash",
        "gemini-3.5-flash",
        "gemini-3.1-flash-lite",
        "gemini-2.0-flash",
    ]

    # Disable safety filters — Gemini's harassment/dangerous-content filter
    # treats security vulnerability analysis as harmful content and refuses.
    # These settings allow the model to process pentest findings without refusal.
    safety_off = [
        types.SafetySetting(category="HARM_CATEGORY_HARASSMENT",        threshold="BLOCK_NONE"),
        types.SafetySetting(category="HARM_CATEGORY_HATE_SPEECH",        threshold="BLOCK_NONE"),
        types.SafetySetting(category="HARM_CATEGORY_SEXUALLY_EXPLICIT",  threshold="BLOCK_NONE"),
        types.SafetySetting(category="HARM_CATEGORY_DANGEROUS_CONTENT",  threshold="BLOCK_NONE"),
    ]

    logger.info("Sending %d findings to Gemini for triaging...", len(enriched_findings))

    targets = _assessment_targets(enriched_findings)
    primary_target = targets[0] if targets else "Target Web Application"
    from datetime import datetime
    today_str = datetime.now().strftime("%d %B %Y")

    # Load scan metadata
    scan_meta = {}
    scan_meta_path = "scan_meta.json"
    if os.path.exists(scan_meta_path):
        try:
            with open(scan_meta_path, "r", encoding="utf-8") as f:
                scan_meta = json.load(f)
        except Exception:
            scan_meta = {}

    # Format the timestamp into a readable date
    raw_date = scan_meta.get("timestamp", scan_meta.get("start_time", scan_meta.get("scan_date", "")))
    if raw_date:
        try:
            # Try ISO format first
            dt = datetime.fromisoformat(raw_date.replace("Z", "+00:00"))
            formatted_date = dt.strftime("%d %B %Y at %H:%M")
        except Exception:
            formatted_date = raw_date  # fallback to raw if parsing fails
    else:
        formatted_date = "Unknown"

    pages_crawled = scan_meta.get("snapshots", scan_meta.get("crawl_snapshots", scan_meta.get("pages_crawled", scan_meta.get("max_depth", "Unknown"))))
    if isinstance(pages_crawled, int) or (isinstance(pages_crawled, str) and pages_crawled.isdigit()):
        pages_crawled = f"{pages_crawled} (max crawl depth: {scan_meta.get('max_depth', pages_crawled)})"
    interactions = scan_meta.get("interactions", scan_meta.get("total_interactions", scan_meta.get("crawl_interactions", "Unknown")))
    if interactions == "Unknown":
        interactions = "Automated DOM & form interaction" if scan_meta.get("active_scan", True) else "N/A (Passive scan only)"
    passive_findings = scan_meta.get("passive_findings", scan_meta.get("passive_count", "Unknown"))
    active_findings = scan_meta.get("active_findings", scan_meta.get("active_count", "Unknown"))
    scan_duration = scan_meta.get("elapsed_seconds", scan_meta.get("duration_s", scan_meta.get("elapsed", "Unknown")))
    finding_count_meta = scan_meta.get("total_findings", scan_meta.get("findings_count", scan_meta.get("finding_count", len(enriched_findings))))
    active_scan = scan_meta.get("active_scan", True)
    scanner_version = scan_meta.get("scanner_version", "1.1")

    # Inject real metadata values into the system instruction template
    system_instruction_rendered = (
        SYSTEM_INSTRUCTION
        .replace("{target_url}", primary_target)
        .replace("{date}", formatted_date if formatted_date != "Unknown" else today_str)
        .replace("{page_count from scan metadata}", str(pages_crawled))
        .replace("{page_count}", str(pages_crawled))
        .replace("{interaction_count}", str(interactions))
        .replace("{scan_duration}", str(formatted_date if formatted_date != "Unknown" else (scan_duration if scan_duration != "Unknown" else raw_date)))
        .replace("{passive_findings_count}", str(passive_findings))
        .replace("{active_findings_count}", str(active_findings))
    )

    meta_summary = (
        f"Scan Metadata:\n"
        f"- Target Application: {primary_target}\n"
        f"- Scan Date / Timestamp: {formatted_date}\n"
        f"- Scanner Version: {scanner_version}\n"
        f"- Active Scan Enabled: {active_scan}\n"
        f"- Pages Crawled / Max Depth: {pages_crawled}\n"
        f"- Interactions Tested: {interactions}\n"
        f"- Total Findings: {finding_count_meta}\n"
        f"- Passive Findings Count: {passive_findings}\n"
        f"- Active Findings Count: {active_findings}\n"
    )

    prompt = (
        f"Generate the complete VAPT assessment report for target '{primary_target}' assessed on '{today_str}'.\n\n"
        f"{meta_summary}\n"
        f"Findings count: {len(enriched_findings)}\n"
        "Remember: Output must begin with `<!-- TRIAGE_METRICS: suppressed=<N> -->`\n\n"
        + _format_findings_for_prompt(enriched_findings)
    )

    report_markdown = None

    for model_name in CANDIDATE_MODELS:
        logger.info("Attempting generation with model: %s", model_name)
        try:
            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=system_instruction_rendered,
                    temperature=0.2,
                    safety_settings=safety_off,
                )
            )
            raw_text = response.text or ""

            # Detect safety refusals — model returned text but it's a refusal, not a report
            refusal_signals = (
                "i cannot fulfill",
                "i'm unable to",
                "i am unable to",
                "i cannot assist",
                "sorry, i cannot",
                "i can't help with",
            )
            if any(s in raw_text.lower()[:300] for s in refusal_signals):
                logger.warning("Model %s returned a safety refusal, trying next model.", model_name)
                continue

            suppressed_count, report_body = _suppressed_count(raw_text, len(enriched_findings))
            report_markdown = report_body
            logger.info("Successfully generated content using %s", model_name)
            break
        except Exception as exc:
            logger.warning("Failed to generate content with %s: %s", model_name, exc)
            continue
            
    if not report_markdown:
        logger.error("All candidate models failed to generate the report.")
        raise RuntimeError("All candidate Gemini models failed to generate the report.")

    # Export to markdown file
    try:
        with open(output_file, "w", encoding="utf-8") as f:
            f.write(report_markdown)
        logger.info("Successfully generated Vulnerability Report: %s", output_file)
    except IOError as exc:
        logger.error("Failed to write report to %s: %s", output_file, exc)
        raise RuntimeError(f"Failed to write vulnerability report to {output_file}") from exc


def main() -> None:
    input_file = "enriched_results.json"
    output_file = "vulnerability_report.md"
    
    logger.info("Starting Phase 3: AI Triage & Report Generation")
    generate_report(input_file, output_file)
    logger.info("Phase 3 complete.")

if __name__ == "__main__":
    main()
